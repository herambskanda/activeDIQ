// about is the About sheet of an XLSX export (spec §8.3): what the file is, who made it, from which scope
// and filters, how fresh the data was, how many rows, and the digest anyone can recompute from the run. It
// holds names, counts and times only, never a cell value of the result. CSV has no About block (a header
// row and data rows only), so it is not passed there.
func (s *Service) about(r run.Run, def run.Definition, q report.Query, e Export) []pexport.AboutLine {
	lines := []pexport.AboutLine{
		{Label: "Report", Value: def.Def.Title},
		{Label: "Report ID", Value: string(def.Def.ID) + "@" + strconv.Itoa(r.DefinitionVer)},
		{Label: "Preset", Value: r.Preset},
		{Label: "Scope applied", Value: orNone(r.ScopeApplied.Summary)},
		{Label: "Filters", Value: filters(q, def.Dataset)},
	}
	fresh := "Not synced yet"
	if r.Freshness != nil && r.Freshness.Label != "" {
		fresh = r.Freshness.Label
	}
	lines = append(lines, pexport.AboutLine{Label: "Freshness", Value: fresh})
	if r.AsOf != nil {
		lines = append(lines, pexport.AboutLine{Label: "Data as of (UTC)", Value: r.AsOf.UTC().Format(time.RFC3339)})
	}
	lines = append(lines,
		pexport.AboutLine{Label: "Generated by", Value: e.CreatedBy},
		pexport.AboutLine{Label: "Generated at (UTC)", Value: s.now().Format(time.RFC3339)},
		pexport.AboutLine{Label: "Row count", Value: strconv.FormatInt(*r.RowCount, 10)},
	)
	if len(q.Hidden) > 0 {
		var hidden []string
		for _, g := range q.Hidden {
			if n := r.HiddenCounts[g.ID]; n > 0 {
				hidden = append(hidden, g.ID+": "+strconv.FormatInt(n, 10))
			}
		}
		if len(hidden) > 0 {
			lines = append(lines, pexport.AboutLine{Label: "Hidden groups", Value: strings.Join(hidden, ", ")})
		}
	}
	return append(lines,
		pexport.AboutLine{Label: "Digest (SHA-256)", Value: hexOf(r.Digest)},
		pexport.AboutLine{Label: "Run ID", Value: r.ID.String()},
	)
}

func orNone(s string) string {
	if s == "" {
		return "None"
	}
	return s
}

// filters renders the query's row filter in words, by column label and operator name, with the values the
// admin chose. A GUID or an enum shows as its ID or label. "None" when the preset and parameters filter
// nothing.
func filters(q report.Query, ds report.Dataset) string {
	if q.Where == nil {
		return "None"
	}
	out := expr(q.Where, ds, 0)
	if out == "" {
		return "None"
	}
	return out
}

func expr(x report.Expr, ds report.Dataset, depth int) string {
	switch t := x.(type) {
	case report.And:
		return join(t.Terms, " AND ", ds, depth)
	case report.Or:
		return join(t.Terms, " OR ", ds, depth)
	case report.Not:
		return "NOT (" + expr(t.Term, ds, depth+1) + ")"
	case report.Cmp:
		return cmp(t, ds)
	}
	return ""
}

func join(terms []report.Expr, sep string, ds report.Dataset, depth int) string {
	parts := make([]string, 0, len(terms))
	for _, t := range terms {
		if p := expr(t, ds, depth+1); p != "" {
			parts = append(parts, p)
		}
	}
	switch len(parts) {
	case 0:
		return ""
	case 1:
		return parts[0]
	}
	s := strings.Join(parts, sep)
	if depth > 0 {
		return "(" + s + ")"
	}
	return s
}

func cmp(c report.Cmp, ds report.Dataset) string {
	label := string(c.Column)
	var col report.Column
	if cc, ok := ds.Column(c.Column); ok {
		col, label = cc, cc.Label
	}
	s := label + " " + c.Op.String()
	switch {
	case len(c.Values) > 0:
		vs := make([]string, len(c.Values))
		for i, v := range c.Values {
			vs[i] = value(v, col)
		}
		return s + " [" + strings.Join(vs, ", ") + "]"
	case c.Value.Type() != report.TypeInvalid:
		return s + " " + value(c.Value, col)
	}
	return s
}

func value(v report.Value, col report.Column) string {
	switch v.Type() {
	case report.TypeText:
		return strconv.Quote(v.Text())
	case report.TypeInt:
		return strconv.FormatInt(v.Int(), 10)
	case report.TypeBool:
		return strconv.FormatBool(v.Bool())
	case report.TypeTime:
		return v.Time().UTC().Format(time.RFC3339)
	case report.TypeEnum:
		for _, e := range col.Enum {
			if e.ID == v.Text() {
				return e.Label
			}
		}
		return v.Text()
	case report.TypeGUID:
		return report.GUIDString(v.GUID())
	}
	return ""
}
