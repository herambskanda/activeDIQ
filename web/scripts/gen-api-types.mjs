// Generates web/src/api/schema.gen.d.ts from the API bundle (ADR-0004 rule 4).
//
//   node scripts/gen-api-types.mjs <bundle.json> <out.d.ts>
//
// tools/gen/api runs this; nothing else should. The bundle is the one input: no tool reads the
// per-tag sources. Open enums (`x-activediq-enum: open`, every enum a response can carry) are
// widened to `"a" | "b" | (string & {})`, so a client built today still type-checks when the
// server adds a value (rule 2). Closed request enums stay closed.
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import openapiTS, { astToString } from "openapi-typescript";

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error("usage: gen-api-types.mjs <bundle.json> <out.d.ts>");
  process.exit(2);
}

const bundle = JSON.parse(readFileSync(input, "utf8"));
const f = ts.factory;

const ast = await openapiTS(bundle, {
  // Header comment of the output; the bundle's own version is not interesting to a reader.
  alphabetize: true,
  immutable: false,
  // Every enum becomes a union of its literal values; an open one gains `(string & {})`.
  enum: false,
  transform(schema) {
    if (schema["x-activediq-enum"] !== "open" || !Array.isArray(schema.enum)) {
      return undefined;
    }
    const literals = schema.enum.map((v) =>
      f.createLiteralTypeNode(f.createStringLiteral(String(v))),
    );
    const unknownString = f.createIntersectionTypeNode([
      f.createKeywordTypeNode(ts.SyntaxKind.StringKeyword),
      f.createTypeLiteralNode([]),
    ]);
    return f.createUnionTypeNode([...literals, f.createParenthesizedType(unknownString)]);
  },
});

const header = "// Code generated by tools/gen/api (openapi-typescript); DO NOT EDIT.\n\n";
writeFileSync(output, header + astToString(ast));
