// scopeMethods are the ReadScope methods whose callers SE1 fixes.
var (
	rendererMethods = map[string]bool{"Terms": true, "Token": true}
	memberMethods   = map[string]bool{"Admits": true, "SearchRoots": true}
)

// exception is a listed departure from a rule. Pending ones are reported as pending on every run, which
// is not a pass; they name the ticket that deletes them. A listed exception that no longer matches
// anything is itself a violation, so the list cannot go stale.
type exception struct {
	Check, Rule, File string
	Pending           bool
	Why               string
	used              bool
}

