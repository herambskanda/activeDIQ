// tree writes files (path -> content) into a fresh module and returns its root.
func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	if _, ok := files["go.mod"]; !ok {
		files["go.mod"] = "module fx.test\n\ngo 1.27.0\n"
	}
	for p, c := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// want asserts that scanning the tree yields exactly one finding of rule (and ff) in file, or none
// when rule is "".
func want(t *testing.T, name string, files map[string]string, ff, rule, file string) {
	t.Helper()
	t.Run(name, func(t *testing.T) {
		fs, err := Scan(tree(t, files), AllChecks())
		if err != nil {
			t.Fatal(err)
		}
		if rule == "" {
			if len(fs) != 0 {
				t.Fatalf("expected no findings, got %v", fs)
			}
			return
		}
		var hit []Finding
		for _, f := range fs {
			if f.Rule == rule {
				hit = append(hit, f)
			}
		}
		if len(hit) == 0 {
			t.Fatalf("expected %s [%s] in %s, got %v", ff, rule, file, fs)
		}
		if hit[0].FF != ff || hit[0].File != file {
			t.Fatalf("expected %s in %s, got %v", ff, file, hit[0])
		}
	})
}

func gofile(imports, body string) string {
	return "package x\n\nimport (\n" + imports + ")\n\n" + body + "\n"
}

