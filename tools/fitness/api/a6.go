package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

const genHeader = "// Code generated by tools/gen/api; DO NOT EDIT."

// checkA6 is ADR-0004 A6 (generated server), the source half. The staleness of a *.gen.go is
// make gen-api-check, as for A5, and is not repeated here. This reads internal/** and cmd/**:
//   - apihost's route constructors are called only from files with the generated header;
//   - Registrar.API (any call of a method named API) is given exactly the module's own api.Bind(...);
//   - a handler package (a module, or a kernel package that has an api subpackage) does not import
//     net/http: only apihost and generated code may;
//   - apihost imports no kernel package that serves API and no module (it uses Ports);
//   - a Go file in an api package carries the generated header, so "a type from an api package" is
//     a generated type for the A7 closure.
func checkA6(t *tree) []Violation {
	var vs []Violation
	root := t.root
	add := func(pos, f string, a ...any) { vs = append(vs, Violation{"A6", pos, fmt.Sprintf(f, a...)}) }
	servesAPI := apiPackageDirs(root)
	fset := token.NewFileSet()
	for _, rel := range goFiles(root, "internal", "cmd") {
		full := filepath.Join(root, filepath.FromSlash(rel))
		b, err := os.ReadFile(full)
		if err != nil {
			add(rel, "cannot read, so A6 cannot be checked: %v", err)
			continue
		}
		f, err := parser.ParseFile(fset, full, b, parser.SkipObjectResolution|parser.ParseComments)
		if err != nil {
			add(rel, "cannot parse, so A6 cannot be checked: %v", err)
			continue
		}
		dir := filepath.ToSlash(filepath.Dir(rel))
		generated := strings.HasPrefix(string(b), genHeader)
		inApihost := dir == "internal/platform/apihost" || strings.HasPrefix(dir, "internal/platform/apihost/")
		inAPIPkg := filepath.Base(dir) == "api" && !inApihost

		if inAPIPkg && !generated {
			add(rel, "a file in an api package without the generated header (%q): an api package is generated code only, handlers live in the module (ADR-0004 A6)", genHeader)
		}

		if apihostName := importName(f, "github.com/skenzeriq/activediq/internal/platform/apihost"); apihostName != "" && !generated && !inApihost {
			ast.Inspect(f, func(n ast.Node) bool {
				sel, ok := n.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				if id, ok := sel.X.(*ast.Ident); ok && id.Name == apihostName && (sel.Sel.Name == "NewRoute" || sel.Sel.Name == "NewTagHandlers") {
					add(fmt.Sprintf("%s:%d", rel, fset.Position(sel.Pos()).Line), "apihost.%s is called from a file without the generated header: routes are built by the generated Bind only (ADR-0004 A6)", sel.Sel.Name)
				}
				return true
			})
		}

		ast.Inspect(f, func(n ast.Node) bool {
			c, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := c.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "API" || len(c.Args) == 0 {
				return true
			}
			if !isOwnBind(c) {
				add(fmt.Sprintf("%s:%d", rel, fset.Position(c.Pos()).Line), "Registrar.API is called with something other than the module's own api.Bind(...) (ADR-0004 A6)")
			}
			return true
		})

		if !inApihost && !generated && importName(f, "net/http") != "" && isHandlerPackage(dir, servesAPI) {
			add(rel, "handler package %s imports net/http: a handler has no request or response, only apihost and generated code may (ADR-0004 A6)", dir)
		}

		if inApihost {
			for _, im := range f.Imports {
				p := strings.Trim(im.Path.Value, "\"`")
				if bad := kernelServingAPI(p, servesAPI); bad != "" {
					add(fmt.Sprintf("%s:%d", rel, fset.Position(im.Pos()).Line), "apihost imports %s, %s: apihost reaches kernel services only through Ports (ADR-0004 A6)", p, bad)
				}
			}
		}
	}
	return vs
}

// isOwnBind reports a call whose only argument is a call of a function named Bind from a package
// named api.
func isOwnBind(c *ast.CallExpr) bool {
	if len(c.Args) != 1 {
		return false
	}
	in, ok := c.Args[0].(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, ok := in.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Bind" {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	return ok && id.Name == "api"
}

const modPath = "github.com/skenzeriq/activediq/"

// apiPackageDirs lists the repository directories (slash paths) named api under internal/modules
// and internal/platform, the generated handler packages.
func apiPackageDirs(root string) map[string]bool {
	out := map[string]bool{}
	for _, d := range goFiles(root, "internal/modules", "internal/platform") {
		dir := filepath.ToSlash(filepath.Dir(d))
		if filepath.Base(dir) == "api" {
			out[dir] = true
		}
	}
	return out
}

// isHandlerPackage: a package of a module, or of a kernel package that has an api subpackage, other
// than the generated api package itself.
func isHandlerPackage(dir string, servesAPI map[string]bool) bool {
	if strings.HasPrefix(dir, "internal/modules/") {
		return filepath.Base(dir) != "api"
	}
	for api := range servesAPI {
		parent := filepath.ToSlash(filepath.Dir(api))
		if (dir == parent || strings.HasPrefix(dir, parent+"/")) && dir != api && filepath.Base(dir) != "api" {
			return true
		}
	}
	return false
}

// kernelServingAPI says why an import is a kernel package that serves API ("" when it is not).
func kernelServingAPI(imp string, servesAPI map[string]bool) string {
	rel, ok := strings.CutPrefix(imp, modPath)
	if !ok {
		return ""
	}
	if strings.HasPrefix(rel, "internal/modules/") {
		return "a module"
	}
	if !strings.HasPrefix(rel, "internal/platform/") || strings.HasPrefix(rel, "internal/platform/apihost") {
		return ""
	}
	for api := range servesAPI {
		parent := filepath.ToSlash(filepath.Dir(api))
		if rel == parent || strings.HasPrefix(rel, parent+"/") {
			return "a kernel package that serves API"
		}
	}
	return ""
}
