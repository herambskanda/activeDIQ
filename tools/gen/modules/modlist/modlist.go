// Package modlist generates the two module lists of the composition root: internal/compose/server/
// modules.gen.go (one Entry per server module) and internal/compose/agent/modules.gen.go (the agent
// module for each component kind). They are the only files that name a module (blueprint §2 rule 5).
//
// A server module is a directory under internal/modules whose non-test Go files declare
// `const ModuleID module.ID`. An agent module is a directory under internal/agentmodules whose non-test
// files declare `const Kind = fleet.Kind<X>`, the component kind it serves. Directories with neither are
// libraries, not modules, and are not listed.
//
// The package is shared by tools/gen/modules (which writes the files) and tools/fitness/modules (M3a,
// ADR-0015 D3, which regenerates them in memory and fails on any byte of difference), so the two cannot
// disagree about what "current" means.
package modlist

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// Header is the first line of both generated files. Go tooling recognises it as generated code.
const Header = "// Code generated by tools/gen/modules; DO NOT EDIT."

// Paths of the two generated files, relative to the repository root.
const (
	ServerFile = "internal/compose/server/modules.gen.go"
	AgentFile  = "internal/compose/agent/modules.gen.go"
)

// AgentModule is one agent module: its package directory name. The component kind it serves is its own
// exported `Kind` constant.
type AgentModule struct {
	ID string // directory name under internal/agentmodules
}

// Lists is what the tree declares.
type Lists struct {
	Server []string      // module IDs (directory names), sorted
	Agent  []AgentModule // sorted by ID
}

// Discover reads the tree at root.
func Discover(root string) (Lists, error) {
	var l Lists
	ids, err := subdirs(filepath.Join(root, "internal", "modules"))
	if err != nil {
		return l, err
	}
	for _, id := range ids {
		ok, _, err := declares(filepath.Join(root, "internal", "modules", id), "ModuleID")
		if err != nil {
			return l, err
		}
		if ok {
			l.Server = append(l.Server, id)
		}
	}
	ids, err = subdirs(filepath.Join(root, "internal", "agentmodules"))
	if err != nil {
		return l, err
	}
	for _, id := range ids {
		ok, _, err := declares(filepath.Join(root, "internal", "agentmodules", id), "Kind")
		if err != nil {
			return l, err
		}
		if ok {
			l.Agent = append(l.Agent, AgentModule{ID: id})
		}
	}
	return l, nil
}

func subdirs(dir string) ([]string, error) {
	es, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range es {
		if e.IsDir() {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out, nil
}

// declares reports whether a non-test file directly in dir declares the package-level constant name, and,
// for a constant whose value is a selector `pkg.X`, returns X.
func declares(dir, name string) (bool, string, error) {
	es, err := os.ReadDir(dir)
	if err != nil {
		return false, "", err
	}
	fset := token.NewFileSet()
	for _, e := range es {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.SkipObjectResolution)
		if err != nil {
			return false, "", err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				for i, id := range vs.Names {
					if id.Name != name {
						continue
					}
					if i < len(vs.Values) {
						if sel, ok := vs.Values[i].(*ast.SelectorExpr); ok {
							return true, sel.Sel.Name, nil
						}
					}
					return true, "", nil
				}
			}
		}
	}
	return false, "", nil
}

// Render returns the bytes of the two generated files for the module path modPath.
func Render(modPath string, l Lists) (server, agent []byte) {
	imp := func(p string) string { return "\t\"" + modPath + "/" + p + "\"\n" }
	var b bytes.Buffer
	b.WriteString(Header + "\n\npackage server\n\nimport (\n")
	imports := []string{"internal/directory", "internal/platform", "internal/platform/module"}
	for _, id := range l.Server {
		imports = append(imports, "internal/modules/"+id)
	}
	sort.Strings(imports)
	for _, p := range imports {
		b.WriteString(imp(p))
	}
	b.WriteString(")\n\n")
	b.WriteString("// generatedModules builds one Entry per directory under internal/modules, passing every module the\n")
	b.WriteString("// same two values (ADR-0003 rules 3 and 4).\n")
	b.WriteString("func generatedModules(deps platform.Deps, dir directory.Services) []module.Entry {\n\treturn []module.Entry{\n")
	for _, id := range l.Server {
		fmt.Fprintf(&b, "\t\t{ID: %s.ModuleID, Module: %s.New(deps, dir)},\n", id, id)
	}
	b.WriteString("\t}\n}\n")
	server = b.Bytes()

	var a bytes.Buffer
	a.WriteString(Header + "\n\n")
	a.WriteString("// This file is the only place in compose/agent that names an agent module (blueprint §2 rule 5).\n\n")
	a.WriteString("package agent\n\nimport (\n")
	aimports := []string{"internal/platform/agent"}
	for _, m := range l.Agent {
		aimports = append(aimports, "internal/agentmodules/"+m.ID)
	}
	sort.Strings(aimports)
	for _, p := range aimports {
		if p == "internal/platform/agent" {
			a.WriteString("\tkernel \"" + modPath + "/" + p + "\"\n")
			continue
		}
		a.WriteString(imp(p))
	}
	a.WriteString(")\n\n")
	a.WriteString("// buildModule returns the module for a component kind. A kind with no module here has no agent.\n")
	a.WriteString("func buildModule(kind string, dcGUID string) (kernel.Module, bool) {\n\tswitch kind {\n")
	for _, m := range l.Agent {
		fmt.Fprintf(&a, "\tcase %s.Kind:\n\t\treturn %s.New(nil, dcGUID), true\n", path.Base(m.ID), path.Base(m.ID))
	}
	a.WriteString("\t}\n\treturn nil, false\n}\n")
	agent = a.Bytes()
	return server, agent
}

// ModulePath reads the module directive of root/go.mod.
func ModulePath(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("%s/go.mod: no module directive", root)
}
