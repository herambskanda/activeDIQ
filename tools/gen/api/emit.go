var initialisms = map[string]bool{
	"id": true, "guid": true, "uuid": true, "url": true, "uri": true, "dn": true, "sid": true, "ip": true,
	"mfa": true, "sso": true, "api": true, "json": true, "http": true, "https": true, "ldap": true, "ou": true,
	"ttl": true, "ad": true, "csv": true, "pdf": true, "html": true, "upn": true, "tls": true, "totp": true,
	"oidc": true, "saml": true, "csrf": true,
}

// words splits camelCase, kebab-case and snake_case into words.
func words(s string) []string {
	var out []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			out = append(out, string(cur))
			cur = nil
		}
	}
	rs := []rune(s)
	for i, r := range rs {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
			continue
		case unicode.IsUpper(r) && len(cur) > 0:
			prev := rs[i-1]
			next := rune(0)
			if i+1 < len(rs) {
				next = rs[i+1]
			}
			if unicode.IsLower(prev) || unicode.IsDigit(prev) || (unicode.IsUpper(prev) && unicode.IsLower(next)) {
				flush()
			}
		}
		cur = append(cur, r)
	}
	flush()
	return out
}

// goName turns a wire name into an exported Go identifier.
func goName(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		lw := strings.ToLower(w)
		if initialisms[lw] {
			b.WriteString(strings.ToUpper(lw))
			continue
		}
		rs := []rune(lw)
		rs[0] = unicode.ToUpper(rs[0])
		b.WriteString(string(rs))
	}
	return b.String()
}

func goIdent(s string) string {
	n := goName(s)
	if n == "" || unicode.IsDigit(rune(n[0])) {
		return "X" + n
	}
	return n
}
