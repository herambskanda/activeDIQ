const generatedHeader = "// Code generated by tools/gen/api; DO NOT EDIT.\n\n"

// Binding maps a shared schema to a Go type that is not emitted from the schema (ADR-0004 rule 4:
// the safe-primitive wire forms, SecretInput and the hand-written scalars). A binding is a
// security-sensitive change. A Pending binding names a type whose package is not built yet: the
// schema is emitted as an ordinary generated type until the owner flips it.
type Binding struct {
	Schema  string
	Import  string
	Type    string
	Secret  bool // the type has Destroy()
	Pending bool
	Owner   string // the ticket or primitive that will own the type, for Pending entries
}

// Config says where everything goes. Paths under Out are slash paths.
type Config struct {
	Root           string // the api/openapi directory
	Out            string // directory the generated tree is rooted at
	Module         string // import path of Out
	ApitypesImport string // the hand-written scalars, Opt and decode helpers
	ApihostImport  string
	SharedDir      string // where shared/ is emitted, relative to Out
	BundlePath     string // relative to Out
	TSOut          string // relative to Out; empty skips TypeScript
	EmitProblems   bool   // emit the problem catalogue constructors (needs apitypes' hand-written glue)
	Bindings       []Binding
}

// unit is one generated Go package: shared/ or one tag.
type unit struct {
	cfg    *Config
	m      *Model
	tag    string // empty for shared
	pkg    string
	imp    string // import path
	dir    string // relative to cfg.Out
	names  map[string]string
	pats   map[string]string
	patSeq []string
	errs   *errList
}

type gofile struct {
	u       *unit
	buf     bytes.Buffer
	imports map[string]string
}

func (u *unit) newFile() *gofile { return &gofile{u: u, imports: map[string]string{}} }

func (f *gofile) p(format string, a ...any) { fmt.Fprintf(&f.buf, format, a...) }

// use registers an import and returns the qualifier to write ("" for the unit's own package).
func (f *gofile) use(importPath string) string {
	if importPath == f.u.imp {
		return ""
	}
	alias := path.Base(importPath)
	switch importPath {
	case "encoding/json/v2":
		alias = "json"
	}
	f.imports[importPath] = alias
	return alias + "."
}

// q qualifies a name of the hand-written apitypes package.
func (f *gofile) apit(name string) string { return f.use(f.u.cfg.ApitypesImport) + name }

func (f *gofile) bytes() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintf(&out, "package %s\n\n", f.u.pkg)
	if len(f.imports) > 0 {
		paths := make([]string, 0, len(f.imports))
		for p := range f.imports {
			paths = append(paths, p)
		}
		sort.Slice(paths, func(i, j int) bool {
			si, sj := !strings.Contains(strings.Split(paths[i], "/")[0], "."), !strings.Contains(strings.Split(paths[j], "/")[0], ".")
			if si != sj {
				return si
			}
			return paths[i] < paths[j]
		})
		out.WriteString("import (\n")
		prev := true
		for i, p := range paths {
			std := !strings.Contains(strings.Split(p, "/")[0], ".")
			if i > 0 && std != prev {
				out.WriteString("\n")
			}
			prev = std
			alias := f.imports[p]
			if alias != path.Base(p) {
				fmt.Fprintf(&out, "\t%s %q\n", alias, p)
			} else {
				fmt.Fprintf(&out, "\t%q\n", p)
			}
		}
		out.WriteString(")\n\n")
	}
	out.Write(f.buf.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: generated code does not parse: %w\n%s", f.u.dir, err, numbered(out.String()))
	}
	return src, nil
}

func numbered(s string) string {
	lines := strings.Split(s, "\n")
	for i := range lines {
		lines[i] = fmt.Sprintf("%4d  %s", i+1, lines[i])
	}
	return strings.Join(lines, "\n")
}

// claim records a Go identifier of the unit and fails on a collision.
func (u *unit) claim(name, what string) {
	if prev, dup := u.names[name]; dup {
		u.errs.addf("%s: the Go name %s is produced by both %s and %s", u.dir, name, prev, what)
		return
	}
	u.names[name] = what
}

func (u *unit) binding(schema string) *Binding {
	for i := range u.cfg.Bindings {
		b := &u.cfg.Bindings[i]
		if b.Schema == schema && !b.Pending {
			return b
		}
	}
	return nil
}

// ownerPkg returns the import path of the unit that declares a component schema.
func (u *unit) ownerImport(s *Schema) string {
	if s.Tag == "" {
		return u.cfg.SharedImport()
	}
	return u.cfg.TagImport(s.Tag)
}

// SharedImport is the import path of the shared package.
func (c *Config) SharedImport() string { return c.Module + "/" + c.SharedDir }

// TagDir maps a tag onto the directory of its generated package (ADR-0004 rule 4).
func TagDir(tag string) string {
	if pkg, ok := strings.CutPrefix(tag, "platform."); ok {
		return "internal/platform/" + pkg + "/api"
	}
	return "internal/modules/" + tag + "/api"
}

// TagImport is the import path of a tag's package.
func (c *Config) TagImport(tag string) string { return c.Module + "/" + TagDir(tag) }

// ref spells a component schema's Go type as seen from f.
func (f *gofile) ref(name string) string {
	u := f.u
	if b := u.binding(name); b != nil {
		return f.use(b.Import) + b.Type
	}
	s := u.m.Schemas[name]
	return f.use(u.ownerImport(s)) + name
}

