// AC2: generated models import only the standard library, apitypes, the bound primitives (secret
// among them) and the shared package; only handlers.gen.go imports apihost.
func TestGeneratedModelsImportOnlyWhatRule4Allows(t *testing.T) {
	cfg := fixtureConfig(t)
	res, err := Generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	allowed := map[string]bool{cfg.ApitypesImport: true, cfg.SharedImport(): true}
	for _, b := range cfg.Bindings {
		allowed[b.Import] = true
	}
	n := 0
	for rel, src := range res.Files {
		if !strings.HasSuffix(rel, ".gen.go") {
			continue
		}
		f, err := goparser.ParseFile(token.NewFileSet(), rel, src, goparser.ImportsOnly)
		if err != nil {
			t.Fatalf("%s: %v", rel, err)
		}
		if !bytes.HasPrefix(src, []byte("// Code generated by tools/gen/api; DO NOT EDIT.\n")) {
			t.Errorf("%s: missing the generated-code header", rel)
		}
		for _, im := range f.Imports {
			p, _ := strconv.Unquote(im.Path.Value)
			std := !strings.Contains(strings.Split(p, "/")[0], ".")
			switch {
			case std || allowed[p]:
			case p == cfg.ApihostImport && strings.HasSuffix(rel, "handlers.gen.go"):
			default:
				t.Errorf("%s imports %s, which generated code may not", rel, p)
			}
			if strings.HasSuffix(rel, "models.gen.go") && p == cfg.ApihostImport {
				t.Errorf("%s: models may not import apihost", rel)
			}
			switch p {
			case "encoding/json", "reflect", "unsafe", "net/http":
				t.Errorf("%s imports %s", rel, p)
			}
		}
		n++
	}
	if n < 3 {
		t.Fatalf("checked %d generated files", n)
	}
}

func TestGenerationIsDeterministic(t *testing.T) {
	cfg := fixtureConfig(t)
	a, err := Generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	for range 3 {
		b, err := Generate(cfg)
		if err != nil {
			t.Fatal(err)
		}
		if len(a.Files) != len(b.Files) {
			t.Fatal("the set of files changed between runs")
		}
		for k, v := range a.Files {
			if !bytes.Equal(v, b.Files[k]) {
				t.Fatalf("%s differs between runs", k)
			}
		}
	}
}

// AC1: a stale, missing or orphaned generated file is reported (this is what `make ci` fails on).
func TestStalenessIsDetected(t *testing.T) {
	cfg := fixtureConfig(t)
	cfg.Out = t.TempDir()
	res, err := Generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if err := Write(cfg, res); err != nil {
		t.Fatal(err)
	}
	if d := Diff(cfg, res); len(d) != 0 {
		t.Fatalf("a freshly written tree must be current: %v", d)
	}
	models := filepath.Join(cfg.Out, "internal", "modules", "widgets", "api", "models.gen.go")
	orig, _ := os.ReadFile(models)
	if err := os.WriteFile(models, append(orig, "\n// hand edit\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	if d := Diff(cfg, res); len(d) != 1 || !strings.Contains(d[0], "models.gen.go: stale") {
		t.Fatalf("a hand-edited generated file is stale: %v", d)
	}
	if err := os.Remove(models); err != nil {
		t.Fatal(err)
	}
	if d := Diff(cfg, res); len(d) != 1 || !strings.Contains(d[0], "models.gen.go: missing") {
		t.Fatalf("a deleted generated file is missing: %v", d)
	}
	orphan := filepath.Join(cfg.Out, "internal", "modules", "widgets", "api", "gone.gen.go")
	if err := os.WriteFile(orphan, []byte("package api\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if d := Diff(cfg, res); len(d) != 2 {
		t.Fatalf("a generated file with no source is reported: %v", d)
	}
	if err := Write(cfg, res); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(orphan); !os.IsNotExist(err) {
		t.Fatal("Write must remove a generated file that has no source")
	}
	if d := Diff(cfg, res); len(d) != 0 {
		t.Fatalf("Write repairs the tree: %v", d)
	}
}

// The real contract's committed outputs are current. `make gen-api` is the repair.
func TestRepositoryTreeIsCurrent(t *testing.T) {
	wd, _ := os.Getwd()
	repo := filepath.Join(wd, "..", "..", "..")
	cfg := DefaultConfig(repo)
	cfg.TSOut = ""
	res, err := Generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if d := Diff(cfg, res); len(d) != 0 {
		t.Fatalf("generated files are out of date (run make gen-api):\n%s", strings.Join(d, "\n"))
	}
}
